/** Small, native pixel glyphs keep the navigation clear even when collapsed. */
export function PixelIcon({ name = 'court', size = 20 }: { name?: string; size?: number }) {
  const rows = GLYPHS[name] ?? GLYPHS.court;
  const d = rows.flatMap((row, y) => [...row].flatMap((cell, x) => cell === '1' ? [`M${x + 2} ${y + 4}h1v1h-1z`] : [])).join('');
  return <svg className="pixel-icon" width={size} height={size} viewBox="0 0 16 16" fill="currentColor" shapeRendering="crispEdges" aria-hidden="true"><path d={d} /></svg>;
}

