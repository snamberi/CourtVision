// Renders src/legal/privacyPolicy.json into public/privacy.html - a plain, crawlable page (no JavaScript
// needed) that ad networks, search engines, and app-store reviewers can open at /privacy.html. The in-app
// page (src/components/PrivacyPolicyPage.tsx) renders the SAME json, so the two can never drift apart.
//
//   npm run generate:legal   -> rewrite public/privacy.html
//
// It runs automatically as part of `npm run build` and `npm run package:windows`.

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const policy = JSON.parse(readFileSync(join(root, 'src', 'legal', 'privacyPolicy.json'), 'utf8'));
const outFile = join(root, 'public', 'privacy.html');

const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

/** Same tiny inline markup as the React renderer: **bold** and [label](https://url). Text is escaped first. */
function inline(text) {
  return esc(text)
    .replace(/\*\*(.+?)\*\*/g, '<strong>$1</strong>')
    .replace(/\[([^\]]+)\]\((https?:\/\/[^)\s]+)\)/g, '<a href="$2" target="_blank" rel="noopener noreferrer">$1</a>');
}

function block(b) {
  switch (b.type) {
    case 'p': return `<p>${inline(b.text)}</p>`;
    case 'ul': return `<ul>\n${b.items.map((i) => `  <li>${inline(i)}</li>`).join('\n')}\n</ul>`;
    case 'table':
      return `<div class="table-wrap"><table>\n<thead><tr>${b.columns.map((c) => `<th>${esc(c)}</th>`).join('')}</tr></thead>\n<tbody>\n${
        b.rows.map((r) => `<tr>${r.map((c, i) => `<td>${i === 1 ? `<code>${esc(c)}</code>` : esc(c)}</td>`).join('')}</tr>`).join('\n')
      }\n</tbody></table></div>`;
    case 'contact':
      return policy.contactEmail
        ? `<p>Email: <a href="mailto:${esc(policy.contactEmail)}">${esc(policy.contactEmail)}</a></p>`
        : '<p>Please use the contact details published on the website or download page where you obtained CourtVision.</p>';
    default: throw new Error(`Unknown block type: ${b.type}`);
  }
}

const toc = policy.sections
  .map((s) => `    <li><a href="#${esc(s.id)}">${esc(s.heading.replace(/^\d+\.\s*/, ''))}</a></li>`).join('\n');
const sections = policy.sections
  .map((s) => `<section id="${esc(s.id)}">\n<h2>${esc(s.heading)}</h2>\n${s.blocks.map(block).join('\n')}\n</section>`).join('\n\n');

const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>${esc(policy.title)} - ${esc(policy.product)}</title>
<meta name="description" content="How ${esc(policy.product)} handles your information: no accounts, saves stay on your device, and how advertising works on the web version.">
<link rel="icon" type="image/png" href="favicon.png">
<!-- GENERATED by scripts/generate-privacy-html.mjs from src/legal/privacyPolicy.json. Edit the JSON, not this file. -->
<style>
  :root { color-scheme: dark; }
  body { margin: 0; background: #08090b; color: #e7e9ee; font: 16px/1.65 system-ui, -apple-system, "Segoe UI", Roboto, sans-serif; }
  main { max-width: 820px; margin: 0 auto; padding: 32px 20px 64px; }
  h1 { font-size: 2rem; margin: 16px 0 4px; }
  h2 { font-size: 1.25rem; margin: 36px 0 8px; padding-top: 8px; border-top: 1px solid #262a33; color: #f5b13d; }
  p, li { color: #d3d7df; }
  ul, ol { padding-left: 1.3rem; }
  li { margin: 6px 0; }
  a { color: #f5b13d; }
  .meta { color: #8b93a3; margin-top: 0; }
  .back { display: inline-block; margin-bottom: 8px; }
  nav.toc { background: #111317; border: 1px solid #262a33; padding: 12px 18px; margin: 20px 0; }
  nav.toc ol { margin: 8px 0 0; columns: 2; column-gap: 32px; }
  .table-wrap { overflow-x: auto; }
  table { border-collapse: collapse; width: 100%; font-size: 0.9rem; }
  th, td { text-align: left; padding: 8px 10px; border: 1px solid #262a33; vertical-align: top; }
  th { background: #111317; }
  code { font-family: ui-monospace, Consolas, monospace; font-size: 0.85em; }
  @media (max-width: 560px) { nav.toc ol { columns: 1; } }
</style>
</head>
<body>
<main>
<a class="back" href="./">&larr; Back to ${esc(policy.product)}</a>
<h1>${esc(policy.title)}</h1>
<p class="meta">${esc(policy.product)} &middot; Last updated: ${esc(policy.lastUpdated)}</p>
${policy.intro.map((t) => `<p>${inline(t)}</p>`).join('\n')}

<nav class="toc" aria-label="Contents">
  <strong>Contents</strong>
  <ol>
${toc}
  </ol>
</nav>

${sections}

<p><a class="back" href="./">&larr; Back to ${esc(policy.product)}</a></p>
</main>
</body>
</html>
`;

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, html);
console.log(`Wrote ${outFile.replace(root + '/', '')}`);
