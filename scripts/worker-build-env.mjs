// Copies the Supabase settings from the build's environment (Cloudflare → Settings → Builds → Variables and secrets)
// into worker/buildEnv.generated.ts, so the Worker has them even when they were only added as Build variables.
// The Worker's own Variables and Secrets still win when both are set. The file is git-ignored and never served.
import { writeFileSync } from 'node:fs';

const NAMES = ['SUPABASE_URL', 'NEXT_PUBLIC_SUPABASE_URL', 'VITE_SUPABASE_URL',
  'SUPABASE_ANON_KEY', 'NEXT_PUBLIC_SUPABASE_ANON_KEY', 'SUPABASE_PUBLISHABLE_KEY', 'NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY', 'VITE_SUPABASE_ANON_KEY',
  'SUPABASE_SERVICE_ROLE_KEY', 'SUPABASE_SECRET_KEY'];
const found = Object.fromEntries(NAMES.map(n => [n, (process.env[n] ?? '').trim()]).filter(([, v]) => v));
writeFileSync(new URL('../worker/buildEnv.generated.ts', import.meta.url),
  `// Generated by scripts/worker-build-env.mjs at build time. Do not commit.\nexport const BUILD_ENV: Record<string, string> = ${JSON.stringify(found)};\n`);
console.log(`worker build env: ${Object.keys(found).join(', ') || 'none'}`);
