// Copies Court Vision's release notes (src/content/whatsNew.ts, the same list the in-game Updates hub shows)
// into site/data/updates-courtvision.js, so the studio site's Updates page stays in step with the game.
// Run after adding a release to the game: node ninefoldvision/scripts/sync-courtvision.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const source = readFileSync(join(root, '../src/content/whatsNew.ts'), 'utf8')

// The RELEASES array is a plain object literal: take it from `= [` to its matching `];`.
const start = source.indexOf('= [', source.indexOf('export const RELEASES')) + 2
let depth = 0, end = start, quote = null
for (let i = start; i < source.length; i++) {
  const ch = source[i]
  if (quote) { if (ch === '\\') i++; else if (ch === quote) quote = null; continue }
  if (ch === '"' || ch === "'" || ch === '`') quote = ch
  else if (ch === '[') depth++
  else if (ch === ']' && --depth === 0) { end = i + 1; break }
}
const releases = new Function(`return ${source.slice(start, end)}`)()

// The headline of each item: its bold lead-in, or its first words (same rule as the game's Updates hub).
const headOf = text => {
  const bold = text.match(/^\*\*([^*]+?)[:.]?\*\*/)
  if (bold) return bold[1].trim().replace(/[:.]$/, '')
  const first = text.replace(/\*\*/g, '').split(/[.:;]\s/)[0]
  return first.length > 60 ? `${first.slice(0, 57).trimEnd()}…` : first
}

const updates = releases.map((r, i) => ({
  game: 'courtvision',
  number: releases.length - i,
  title: r.title,
  theme: r.theme || null,
  items: r.items.map(text => ({ head: headOf(text), text })),
}))

writeFileSync(join(root, 'site/data/updates-courtvision.js'),
  '// Generated by ninefoldvision/scripts/sync-courtvision.mjs from src/content/whatsNew.ts. Do not edit by hand.\n' +
  `window.NFV_GAME_UPDATES = window.NFV_GAME_UPDATES || {};\nwindow.NFV_GAME_UPDATES.courtvision = ${JSON.stringify(updates, null, 1)};\n`)
console.log(`Court Vision: ${updates.length} updates`)
